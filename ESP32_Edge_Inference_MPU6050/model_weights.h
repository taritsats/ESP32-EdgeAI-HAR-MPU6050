// Fungsi Inferensi Ringan MLP pada Edge Device
inline int predictActivity(const float features[20], float probs[3]) {
    // 1. Standarisasi Fitur (Z-score Normalization)
    float z[20];
    for (int i = 0; i < 20; i++) {
        z[i] = (features[i] - SCALER_MEAN[i]) / SCALER_SCALE[i];
    }

    // 2. Hidden Layer 1 (20 -> 16, ReLU)
    float h1[16];
    for (int j = 0; j < 16; j++) {
        float sum = B1[j];
        for (int i = 0; i < 20; i++) {
            sum += z[i] * W1[i][j];
        }
        h1[j] = (sum > 0.0f) ? sum : 0.0f; // ReLU
    }

    // 3. Hidden Layer 2 (16 -> 8, ReLU)
    float h2[8];
    for (int j = 0; j < 8; j++) {
        float sum = B2[j];
        for (int i = 0; i < 16; i++) {
            sum += h1[i] * W2[i][j];
        }
        h2[j] = (sum > 0.0f) ? sum : 0.0f; // ReLU
    }

    // 4. Output Layer (8 -> 3, Softmax)
    float logits[3];
    float max_logit = -1e9f;
    for (int j = 0; j < 3; j++) {
        float sum = B3[j];
        for (int i = 0; i < 8; i++) {
            sum += h2[i] * W3[i][j];
        }
        logits[j] = sum;
        if (sum > max_logit) max_logit = sum;
    }

    // Softmax Stabil Numerik
    float exp_sum = 0.0f;
    for (int j = 0; j < 3; j++) {
        probs[j] = expf(logits[j] - max_logit);
        exp_sum += probs[j];
    }

    int best_class = 0;
    float max_p = 0.0f;
    for (int j = 0; j < 3; j++) {
        probs[j] /= exp_sum;
        if (probs[j] > max_p) {
            max_p = probs[j];
            best_class = j;
        }
    }
    return best_class;
}

